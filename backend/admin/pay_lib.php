function pay_settings_get(PDO $pdo): array {
    $d = ['vat_percent' => '0', 'discount_enabled' => '1', 'gateway_enabled' => '1', 'card_enabled' => '1', 'sheba_enabled' => '1'];
    foreach ($pdo->query('SELECT k, v FROM pay_settings')->fetchAll() as $r) $d[$r['k']] = (string)$r['v'];
    return $d;
}
function pay_setting_set(PDO $pdo, string $k, string $v): void {
    $pdo->prepare('INSERT INTO pay_settings (k, v) VALUES (?, ?) ON DUPLICATE KEY UPDATE v = VALUES(v)')->execute([$k, $v]);
}

/** پیام به یک مشتری با سیستم پیام‌رسانی موجود (announcements) */
function pay_notify(PDO $pdo, int $customerId, string $title, string $body): void {
    ensure_message_tables($pdo);
    $exp = (new DateTime())->modify('+30 days')->format('Y-m-d H:i:s');
    $pdo->prepare('INSERT INTO announcements (customer_id, title, body, link_url, link_label, kind, created_at, expires_at, active) VALUES (?,?,?,NULL,NULL,\'info\',NOW(),?,1)')
        ->execute([$customerId, mb_substr($title, 0, 120), mb_substr($body, 0, 2000), $exp]);
}

function pay_clean_card(string $s): string { return preg_replace('/\D+/', '', pay_en($s)) ?? ''; }
function pay_clean_sheba(string $s): string {
    $s = strtoupper(preg_replace('/[\s\-]+/', '', pay_en($s)) ?? '');
    if (preg_match('/^\d{24}$/', $s)) $s = 'IR' . $s;
    return $s;
}

